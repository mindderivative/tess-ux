#!/usr/bin/env python3
"""Generate the Defaults Matrix note from the Dimensions and defaults tables.

Usage:
  python3 tools/defaults_matrix.py [vault root]           write the note
  python3 tools/defaults_matrix.py [vault root] --check   exit 1 if the note is stale

Standard library only. Reads the `## Dimensions and defaults` table of every
component note (see `_templates/Component.md`) and writes
`20 Foundations and Tokens/Defaults Matrix.md`: one table per property, one row
per component part, columns for the three density levels. It also checks that
every value has a declared origin: a token in the Token column or a Source
(the lint already requires the Source cell). Rows whose Token cell is `-` and
whose value is not N/A are listed in a final table so that a value that comes
from no token is visible. The note is generated: edit the component notes, not
the matrix.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lint_vault as lv  # noqa: E402

OUT = "20 Foundations and Tokens/Defaults Matrix.md"
UPDATED = "2026-11-22"


def collect(root: Path):
    rows = []
    for n in lv.collect_notes(root):
        if not n.rel.startswith(lv.COMPONENT_DIR + "/") or n.fm_scalar("type") != "component":
            continue
        if n.stem in ("Inventory", lv.COMPONENT_DIR):
            continue
        parsed = lv.parse_dimensions(n)
        if parsed is None:
            continue
        _, trs = parsed
        for _, cells in trs[1:]:
            if len(cells) == 8 and cells[1] in lv.DIM_PROPS:
                rows.append((n.stem, *cells))
    return rows


def esc(s: str) -> str:
    return s.replace("|", "/")


def render(root: Path) -> str:
    rows = collect(root)
    comps = sorted({r[0] for r in rows})
    out = [
        "---",
        "title: Defaults Matrix",
        "type: tokens",
        "status: draft",
        "owner: phil",
        "created: 2026-11-22",
        f"updated: {UPDATED}",
        "tags: [tokens, generated]",
        'related: ["[[Spacing and Density]]", "[[Typography]]", "[[Shape]]", "[[Elevation]]"]',
        "depends_on: []",
        "---",
        "",
        "# Defaults Matrix",
        "",
        "> [!warning] Generated note",
        "> Generated by `tools/defaults_matrix.py` from the `Dimensions and defaults` table of each component note. Do not edit it: edit the component note and run the script. CI checks that it is current.",
        "",
        f"{len(rows)} rows from {len(comps)} component notes. Lengths are in dp, `padding` is top right bottom left, `font` is size/line height/weight/tracking, `elevation` is the level 0 to 5.",
        "",
    ]
    for prop in sorted(lv.DIM_PROPS, key=lambda p: (["height", "min width", "min height", "padding", "margin", "gap", "border width", "border color", "corner radius", "font", "icon size", "elevation"]).index(p)):
        pr = sorted([r for r in rows if r[2] == prop], key=lambda r: (r[0].lower(), r[1]))
        out += [f"## {prop.capitalize()}", ""]
        if not pr:
            out += ["No component note has a row for this property yet.", ""]
            continue
        out += ["| Component | Part | Token | Default | Compact | Dense | Source | Settable from Python |", "|---|---|---|---|---|---|---|---|"]
        for comp, part, _, tok, d, c, ds, src, st in pr:
            out.append(f"| [[{comp}]] | {esc(part)} | {esc(tok)} | {esc(d)} | {esc(c)} | {esc(ds)} | {esc(src)} | {esc(st)} |")
        out.append("")
    orphan = [r for r in rows if r[3] in ("-", "") and not lv.NA.match(r[4])]
    out += ["## Values without a token", "",
            "Rows whose Token cell is `-` and whose default is a value, not N/A. Each has a Source (the lint requires it); the list shows which values are not yet tokens.", ""]
    if orphan:
        out += ["| Component | Part | Property | Default | Source |", "|---|---|---|---|---|"]
        for comp, part, prop, _, d, _, _, src, _st in sorted(orphan, key=lambda r: (r[0].lower(), r[2])):
            out.append(f"| [[{comp}]] | {esc(part)} | {prop} | {esc(d)} | {esc(src)} |")
    else:
        out.append("None.")
    out += ["", "Back to [[20 Foundations and Tokens]].", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    root = Path(args[0]).resolve() if args else Path(__file__).resolve().parent.parent
    text = render(root)
    path = root / OUT
    if "--check" in argv:
        cur = path.read_text(encoding="utf-8") if path.exists() else ""
        if cur != text:
            print(f"{OUT} is stale: run python3 tools/defaults_matrix.py", file=sys.stderr)
            return 1
        print("Defaults Matrix is current")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
